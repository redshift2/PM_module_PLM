-- Engineering file registry. The part's CAD version and lifecycle remain authoritative.
-- References use existing PLM part and attachment IDs; existing attachments are untouched.
CREATE TABLE IF NOT EXISTS plm_cad_version_file (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_id BIGINT NOT NULL,
    attachment_id BIGINT NOT NULL,
    cad_major_version INTEGER NOT NULL,
    cad_minor_version INTEGER NOT NULL,
    file_type VARCHAR(16) NOT NULL,
    original_name VARCHAR(512) NOT NULL,
    content_sha_one VARCHAR(40),
    generated_by_job_id VARCHAR(128),
    date_created TIMESTAMP,
    CONSTRAINT fk_plm_cad_file_part FOREIGN KEY (part_id) REFERENCES plm_free_cad_part(id),
    CONSTRAINT fk_plm_cad_file_attachment FOREIGN KEY (attachment_id) REFERENCES attachment(id)
);
CREATE INDEX IF NOT EXISTS idx_plm_cad_file_version ON plm_cad_version_file(part_id, cad_major_version, cad_minor_version, file_type);
