-- V001: Add CAD lifecycle fields without deleting existing part history.
-- H2 auto-commits DDL; each statement must be safe to repeat after interruption.
ALTER TABLE PLM_FREE_CAD_PART ADD COLUMN IF NOT EXISTS MAJOR_VERSION INTEGER DEFAULT 1;
ALTER TABLE PLM_FREE_CAD_PART ADD COLUMN IF NOT EXISTS MINOR_VERSION INTEGER DEFAULT 0;
ALTER TABLE PLM_FREE_CAD_PART ADD COLUMN IF NOT EXISTS LIFECYCLE_STATE VARCHAR(255) DEFAULT 'WIP';
ALTER TABLE PLM_FREE_CAD_PART ADD COLUMN IF NOT EXISTS CHECKED_OUT_BY_ID BIGINT;
ALTER TABLE PLM_FREE_CAD_PART ADD COLUMN IF NOT EXISTS CHECKED_OUT_AT TIMESTAMP;
ALTER TABLE PLM_FREE_CAD_PART ADD COLUMN IF NOT EXISTS RELEASED_BY_ID BIGINT;
ALTER TABLE PLM_FREE_CAD_PART ADD COLUMN IF NOT EXISTS RELEASED_AT TIMESTAMP;

UPDATE PLM_FREE_CAD_PART
SET MAJOR_VERSION = COALESCE(MAJOR_VERSION, 1),
    MINOR_VERSION = COALESCE(MINOR_VERSION, 0),
    LIFECYCLE_STATE = COALESCE(LIFECYCLE_STATE, 'WIP')
WHERE MAJOR_VERSION IS NULL
   OR MINOR_VERSION IS NULL
   OR LIFECYCLE_STATE IS NULL;
